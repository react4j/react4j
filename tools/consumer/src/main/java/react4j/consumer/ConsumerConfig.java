package react4j.consumer;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import org.jspecify.annotations.NullMarked;

@NullMarked
public final class ConsumerConfig {
    private ConsumerConfig() {}

    public static void main(String[] args) throws IOException {
        if (args.length != 2) {
            throw new IllegalArgumentException("Expected React4j checkout and application directory");
        }
        final var source = Path.of(args[0]).toRealPath();
        final var application = Path.of(args[1]).toRealPath();
        if (source.equals(application)) {
            throw new IllegalArgumentException("Application must be a separate checkout");
        }
        final var output = application.resolve("third_party/react4j");
        final var patches = output.resolve("patches");
        final var module = Files.readString(source.resolve("MODULE.bazel"));
        final var boundary = module.indexOf("# --- depgen-generated repository rules start ---");
        if (boundary < 0 || !module.startsWith("module(name = \"react4j\")\n")) {
            throw new IOException("Unexpected React4j module layout");
        }
        final var configuration = module.substring(module.indexOf('\n') + 1, boundary)
                .replace("//third_party/bazel/patches:", "//third_party/react4j/patches:")
                .replace("//:maven_install.json", "//third_party/react4j:maven_install.json")
                .replace("known_contributing_modules = [", "known_contributing_modules = [\n        \"react4j\",");
        Files.createDirectories(patches);
        Files.writeString(
                output.resolve("dependencies.MODULE.bazel"),
                "# Generated by React4j tools/export_bazel_config.sh; regenerate when updating React4j.\n"
                        + configuration);
        Files.copy(
                source.resolve("maven_install.json"),
                output.resolve("maven_install.json"),
                StandardCopyOption.REPLACE_EXISTING);
        try (var files = Files.list(patches)) {
            for (final var file : files.filter(path -> path.toString().endsWith(".patch")).toList()) {
                if (!Files.isRegularFile(source.resolve("third_party/bazel/patches").resolve(file.getFileName()))) {
                    Files.delete(file);
                }
            }
        }
        try (var files = Files.list(source.resolve("third_party/bazel/patches"))) {
            for (final var file : files.filter(path -> path.toString().endsWith(".patch"))
                    .sorted()
                    .toList()) {
                Files.copy(file, patches.resolve(file.getFileName()), StandardCopyOption.REPLACE_EXISTING);
            }
        }
        Files.writeString(
                patches.resolve("BUILD.bazel"),
                "exports_files(glob([\"*.patch\"]), visibility = [\"//visibility:public\"])\n");
        Files.writeString(
                output.resolve("BUILD.bazel"),
                "exports_files([\"dependencies.MODULE.bazel\", \"maven_install.json\"], visibility ="
                        + " [\"//visibility:public\"])\n");
        System.out.println("Generated " + output
                + "; include its dependencies.MODULE.bazel from the application root module and use the same"
                + " React4j revision.");
    }
}
